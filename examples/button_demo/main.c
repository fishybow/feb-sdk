static void draw_center_banner(uint8_t key) {
    const uint8_t *left;
    const uint8_t *mid;
    const uint8_t *right;

    switch (key) {
        case FEB_KEY_UP:
            left = B_UP_L; mid = B_UP_M; right = B_UP_R;
            break;
        case FEB_KEY_DOWN:
            left = B_DOWN_L; mid = B_DOWN_M; right = B_DOWN_R;
            break;
        case FEB_KEY_BACK:
            left = B_BACK_L; mid = B_BACK_M; right = B_BACK_R;
            break;
        case FEB_KEY_OK:
            left = B_OK_L; mid = B_OK_M; right = B_OK_R;
            break;
        default:
            left = B_INIT_L; mid = B_INIT_M; right = B_INIT_R;
            break;
    }

    feb_draw_sprite16(40, 24, left);
    feb_draw_sprite16(56, 24, mid);
    feb_draw_sprite16(72, 24, right);
}

int main(void) {
    uint8_t total_presses = 0;
    uint8_t last_key = 0;
    uint8_t up_count = 0;
    uint8_t down_count = 0;
    uint8_t left_count = 0;
    uint8_t right_count = 0;

    feb_set_high_res(true);
    feb_clear_screen();

    while (1) {
        /* Draw directional button press counters on display edges:
         * Top:    UP count   (x=62, y=10)
         * Left:   BACK count (x=24, y=30)
         * Right:  OK count   (x=100, y=30)
         * Bottom: DOWN count (x=62, y=48)
         */
        feb_draw_digit(62, 10, up_count & 0x0F);
        feb_draw_digit(24, 30, left_count & 0x0F);
        feb_draw_digit(100, 30, right_count & 0x0F);
        feb_draw_digit(62, 48, down_count & 0x0F);

        /* Center: Button name and CHIP-8 key code */
        draw_center_banner(last_key);

        uint8_t key = feb_wait_key();

        /* XOR erase previous state before redrawing */
        feb_draw_digit(62, 10, up_count & 0x0F);
        feb_draw_digit(24, 30, left_count & 0x0F);
        feb_draw_digit(100, 30, right_count & 0x0F);
        feb_draw_digit(62, 48, down_count & 0x0F);
        draw_center_banner(last_key);

        total_presses++;
        last_key = key;

        switch (key) {
            case FEB_KEY_UP:
                up_count++;
                break;
            case FEB_KEY_DOWN:
                down_count++;
                break;
            case FEB_KEY_LEFT:
                left_count++;
                break;
            case FEB_KEY_RIGHT:
                right_count++;
                break;
            default:
                break;
        }
    }

    return 0;
}

