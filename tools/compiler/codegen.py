    def is_simple_arg(self, arg, target_reg, ctx):
        if not arg:
            return True
        t = arg.get("type")
        if t == "num":
            return True
        if t == "ident":
            name = arg["name"]
            loc = ctx.get("locals", {}).get(name)
            if loc:
                if target_reg not in ctx.get("locals", {}).values():
                    return True
                if loc == target_reg:
                    return True
        return False

    def compile_call_args(self, args, target_regs, ctx):
        out = ctx["out"]
        depth = ctx.get("call_depth", 0)
        eval_ctx = dict(ctx)
        eval_ctx["call_depth"] = depth + 1

        saved_indices = set()
        for i, (arg, target_reg) in enumerate(zip(args, target_regs)):
            if not self.is_simple_arg(arg, target_reg, ctx):
                saved_indices.add(i)
                self.compile_expr_into(arg, "v0", eval_ctx)
                buf_name = f"__ARG_{depth}_{i}"
                self.call_arg_buffers.add(buf_name)
                out.append(f"        load i, {buf_name}")
                out.append("        save v0")

        for i, (arg, target_reg) in enumerate(zip(args, target_regs)):
            if i in saved_indices:
                buf_name = f"__ARG_{depth}_{i}"
                out.append(f"        load i, {buf_name}")
                out.append("        restore v0")
                if target_reg != "v0":
                    out.append(f"        load {target_reg}, v0")
            else:
                self.compile_expr_into(arg, target_reg, ctx)

    def compile_call(self, call_node, dest_reg, ctx):
        out = ctx["out"]
        func_name = call_node["func"]["name"]
        args = call_node["args"]

        # ---------------------------------------------------------------------
        # Flashiibo FEB SDK Built-in APIs
        # ---------------------------------------------------------------------
        if func_name in ("feb_set_high_res", "feb_set_hires"):
            # feb_set_high_res(bool enable)
            if args and args[0].get("val") == 0:
                out.append("        low")
            else:
                out.append("        high")
            return dest_reg

        if func_name in ("feb_exit", "feb_quit"):
            out.append("        exit")
            return dest_reg

        if func_name == "feb_clear_screen":
            out.append("        cls")
            return dest_reg

        if func_name == "feb_wait_key":
            out.append(f"        load {dest_reg}, key")
            return dest_reg

        if func_name in ("feb_get_keys", "feb_read_buttons"):
            out.append(f"        getkeys {dest_reg}")
            return dest_reg

        if func_name in ("feb_set_delay_timer", "feb_set_delay"):
            self.compile_call_args([args[0]], ["v0"], ctx)
            out.append("        load dt, v0")
            return dest_reg

        if func_name in ("feb_get_delay_timer", "feb_get_delay"):
            out.append(f"        load {dest_reg}, dt")
            return dest_reg

        if func_name in ("feb_delay_frames", "feb_sleep"):
            self.compile_call_args([args[0]], ["v0"], ctx)
            lbl_loop = self.new_label("DELAY_LOOP")
            out.append("        load dt, v0")
            out.append(f"{lbl_loop}:")
            out.append("        load v0, dt")
            out.append("        skip.eq v0, 0")
            out.append(f"        jump {lbl_loop}")
            return dest_reg

        if func_name == "feb_draw_sprite":
            # feb_draw_sprite(x, y, sprite, height) or (x, y, height, sprite)
            self.compile_call_args([args[0], args[1]], ["va", "vb"], ctx)
            if args[2].get("type") == "ident":
                sprite_label = args[2]["name"].upper()
                h = args[3]["val"] if len(args) > 3 and args[3].get("type") == "num" else 8
            else:
                sprite_label = args[3]["name"].upper() if len(args) > 3 and "name" in args[3] else "SPRITE"
                h = args[2]["val"] if args[2].get("type") == "num" else 8
            out.append(f"        load i, {sprite_label}")
            out.append(f"        draw va, vb, {h}")
            if dest_reg != "vf":
                out.append(f"        load {dest_reg}, vf")
            return dest_reg

        if func_name == "feb_draw_sprite16":
            # feb_draw_sprite16(x, y, sprite)
            self.compile_call_args([args[0], args[1]], ["va", "vb"], ctx)
            if args[2]["type"] == "ident":
                name = args[2]["name"]
                sprite_label = name.upper()
                out.append(f"        load i, {sprite_label}")
            out.append("        draw va, vb, 0")
            if dest_reg != "vf":
                out.append(f"        load {dest_reg}, vf")
            return dest_reg

        if func_name in ("feb_draw_digit", "feb_draw_num"):
            # feb_draw_digit(x, y, digit)
            self.compile_call_args([args[0], args[1], args[2]], ["va", "vb", "vc"], ctx)
            out.append("        hex vc")
            out.append("        draw va, vb, 5")
            return dest_reg

        if func_name == "feb_set_draw_mode":
            self.compile_call_args([args[0]], ["va"], ctx)
            out.append("        drawmode va")
            return dest_reg

        if func_name == "feb_draw_pixel":
            self.compile_call_args([args[0], args[1]], ["va", "vb"], ctx)
            out.append("        pixel va")
            return dest_reg

        if func_name == "feb_draw_line":
            self.compile_call_args([args[0], args[1], args[2], args[3]], ["va", "vb", "vc", "vd"], ctx)
            out.append("        line va")
            return dest_reg

        if func_name == "feb_draw_hline":
            self.compile_call_args([args[0], args[1], args[2]], ["va", "vb", "vc"], ctx)
            out.append("        hline va")
            return dest_reg

        if func_name == "feb_draw_vline":
            self.compile_call_args([args[0], args[1], args[2]], ["va", "vb", "vc"], ctx)
            out.append("        vline va")
            return dest_reg

        if func_name == "feb_draw_rect":
            self.compile_call_args([args[0], args[1], args[2], args[3]], ["va", "vb", "vc", "vd"], ctx)
            out.append("        rect va")
            return dest_reg

        if func_name == "feb_fill_rect":
            self.compile_call_args([args[0], args[1], args[2], args[3]], ["va", "vb", "vc", "vd"], ctx)
            out.append("        fillrect va")
            return dest_reg

        if func_name == "feb_draw_circle":
            self.compile_call_args([args[0], args[1], args[2]], ["va", "vb", "vc"], ctx)
            out.append("        circle va")
            return dest_reg

        if func_name == "feb_fill_circle":
            self.compile_call_args([args[0], args[1], args[2]], ["va", "vb", "vc"], ctx)
            out.append("        disc va")
            return dest_reg

        if func_name == "feb_test_pixel":
            self.compile_call_args([args[0], args[1]], ["va", "vb"], ctx)
            out.append("        testpixel va")
            if dest_reg != "vf":
                out.append(f"        load {dest_reg}, vf")
            return dest_reg

        if func_name in ("feb_draw_string", "feb_draw_text"):
            # feb_draw_string(x, y, str, font)
            self.compile_call_args([args[0], args[1], args[3]], ["va", "vb", "vc"], ctx)
            # String label
            if args[2]["type"] == "str":
                str_lbl = args[2]["label"]
                out.append(f"        load i, {str_lbl}")
            elif args[2]["type"] == "ident":
                str_lbl = args[2]["name"].upper()
                out.append(f"        load i, {str_lbl}")
            out.append("        text va")
            if dest_reg != "va":
                out.append(f"        load {dest_reg}, va")
            return dest_reg

        if func_name in ("feb_draw_char", "feb_draw_character"):
            # feb_draw_char(x, y, ch, font)
            self.compile_call_args([args[0], args[1], args[2], args[3]], ["va", "vb", "vc", "vd"], ctx)
            out.append("        char va")
            if dest_reg != "va":
                out.append(f"        load {dest_reg}, va")
            return dest_reg

        if func_name in ("feb_string_width", "feb_str_width"):
            # feb_string_width(str, font)
            self.compile_call_args([args[1]], ["va"], ctx)
            if args[0]["type"] == "str":
                str_lbl = args[0]["label"]
                out.append(f"        load i, {str_lbl}")
            elif args[0]["type"] == "ident":
                str_lbl = args[0]["name"].upper()
                out.append(f"        load i, {str_lbl}")
            out.append("        textlen va")
            if dest_reg != "va":
                out.append(f"        load {dest_reg}, va")
            return dest_reg

        if func_name == "feb_draw_number":
            # feb_draw_number(x, y, num, font)
            self.compile_call_args([args[0], args[1], args[2], args[3]], ["va", "vb", "vd", "vc"], ctx)
            if args[2]["type"] == "num":
                out.append(f"        load i, {args[2]['val'] & 0xFFF}")
            else:
                out.append("        load i, 0")
                out.append("        add i, vd")
            out.append("        num va")
            if dest_reg != "va":
                out.append(f"        load {dest_reg}, va")
            return dest_reg

        if func_name == "feb_rand":
            mask = args[0]["val"] if args[0]["type"] == "num" else 0xFF
            out.append(f"        rnd {dest_reg}, {mask & 0xFF}")
            return dest_reg

        if func_name == "feb_save_flags":
            # feb_save_flags(data, len) or feb_save_flags(path, data, len)
            len_val = args[-1]["val"] if args[-1]["type"] == "num" else 1
            first_arg = args[1] if len(args) == 3 else args[0]
            if first_arg["type"] == "addrof":
                target = first_arg["target"]
                if target["type"] == "ident":
                    var_name = target["name"]
                    if var_name in ctx["locals"]:
                        reg = ctx["locals"][var_name]
                        out.append(f"        load v0, {reg}")
                    elif var_name in self.globals:
                        out.append(f"        load i, {var_name.upper()}")
                        out.append("        restore v0")
                elif target["type"] == "field":
                    st_target = target["target"]
                    st_field = target["field"]
                    if st_target["type"] == "ident":
                        var_name = st_target["name"]
                        if var_name in self.globals and self.globals[var_name]["type"] == "struct":
                            st_name = self.globals[var_name]["struct_name"]
                            offset = self.struct_types[st_name]["fields"][st_field]["offset"]
                            label = var_name.upper()
                            loc_str = label if offset == 0 else f"{label} + {offset}"
                            out.append(f"        load i, {loc_str}")
                            out.append("        restore v0")
            out.append("        saveflags v0")
            return dest_reg

        if func_name == "feb_load_flags":
            len_val = args[-1]["val"] if args[-1]["type"] == "num" else 1
            first_arg = args[1] if len(args) == 3 else args[0]
            out.append("        loadflags v0")
            if first_arg["type"] == "addrof":
                target = first_arg["target"]
                if target["type"] == "ident":
                    var_name = target["name"]
                    if var_name in ctx["locals"]:
                        reg = ctx["locals"][var_name]
                        out.append(f"        load {reg}, v0")
                    elif var_name in self.globals:
                        out.append(f"        load i, {var_name.upper()}")
                        out.append("        save v0")
                elif target["type"] == "field":
                    st_target = target["target"]
                    st_field = target["field"]
                    if st_target["type"] == "ident":
                        var_name = st_target["name"]
                        if var_name in self.globals and self.globals[var_name]["type"] == "struct":
                            st_name = self.globals[var_name]["struct_name"]
                            offset = self.struct_types[st_name]["fields"][st_field]["offset"]
                            label = var_name.upper()
                            loc_str = label if offset == 0 else f"{label} + {offset}"
                            out.append(f"        load i, {loc_str}")
                            out.append("        save v0")
            return dest_reg

        # ---------------------------------------------------------------------
        # User-Defined Function Call
        # ---------------------------------------------------------------------
        target_func = func_name.upper()
        caller = ctx.get("func")
        has_frame = bool(caller and ctx.get("locals"))
        if has_frame:
            self.frame_buffers.add(caller)
            frame_lbl = f"FRAME_{caller.upper()}"
            out.append(f"        load i, {frame_lbl}")
            out.append("        save v9")

        # Compile arguments into v1, v2, v3...
        arg_regs = [f"v{i}" for i in range(1, len(args) + 1)]
        self.compile_call_args(args, arg_regs, ctx)

        out.append(f"        call {target_func}")
        if has_frame:
            out.append("        load ve, v0")
            out.append(f"        load i, {frame_lbl}")
            out.append("        restore v9")
            out.append("        load v0, ve")

        if dest_reg != "v0":
            out.append(f"        load {dest_reg}, v0")
        return dest_reg

